def template_check(kind, skill=S):
    """Compare templates/<kind>/{hooks/domain.ts, hooks/fixtures.ts, types/index.d.ts} with the output of the kind defaults.
    Return a list of problem lines (empty when each file equals the generated one)."""
    tpl = os.path.join(skill, 'templates', kind)
    try:
        with open(os.path.join(tpl, '.claude-plugin', 'plugin.json'), encoding='utf-8') as fh:
            name = json.load(fh)['name']
    except (OSError, ValueError, KeyError) as e:
        return [f'templates/{kind}: no readable plugin.json ({e})']
    m = Model(validate(defaults(kind), kind), kind, name, plugin=name)
    probs = []
    for rel, text in generate_files(m, skill).items():
        if rel == 'journey.py':
            continue
        have = _read(os.path.join(tpl, rel))
        if have is None:
            probs.append(f'templates/{kind}/{rel} is missing')
        elif have != text:
            a, b = have.split('\n'), text.split('\n')
            at = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
            probs.append(f'templates/{kind}/{rel} line {at + 1}: template {a[at] if at < len(a) else "<end>"!r} · generated {b[at] if at < len(b) else "<end>"!r}')
    return probs


# ---------------------------------------------------------------- the subcommand


def _plural_word(n, word):
    return f'{n} {word}' + ('' if n == 1 else 's')


def domain_notes(d, kind):
    """Two notes for the author (D13): which action the role fails makes fail, and the roles that no scenario has."""
    roles = [s['role'] for s in d['scenarios']]
    notes = []
    if 'fails' in roles and d['actions']:
        notes.append(f"note: role fails makes '{d['actions'][0]['verb']}' fail once (the first of --actions)")
    missing = [r for r in KIND_ROLES[kind] if r not in roles and r not in ('fails', 'idle', 'deny')]
    if missing:
        notes.append(f"note: no scenario with role {', '.join(missing)}: the journey has no screen for them")
    return notes


def cmd_domain(ctx, args):
    cfg, wb = ctx.cfg, ctx.wb
    kind = cfg['kind']
    if kind not in DOMAIN_KINDS:
        raise Fail(f'kind {kind} has no domain block (kind mixed keeps the round 1 path)', 'none', 2)
