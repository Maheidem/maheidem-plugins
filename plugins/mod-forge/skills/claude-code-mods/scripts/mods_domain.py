#!/usr/bin/env python3 -I
"""mods_domain.py: the domain of a mod, and the subcommand domain (round 2 design, section 1).

The domain block of mod.json holds what the mod is about: the noun, the row fields, the actions, the scenarios.
This module reads the block and writes the files that depend on it. Nobody edits those files by hand.

  mods.py domain [flags]          write hooks/fixtures.ts, hooks/domain.ts, types/index.d.ts, journey.py, the marker tests,
                                  and the scenarios and screens of mod.json (the flags replace keys of the block first)
  mods.py domain --check          write nothing: report each generated file that differs from the disk

mods_setup.py (new) uses the same functions: parse_flags, defaults, validate, write, strip.
The same input gives the same bytes. No clock, no random.

  parse_flags(args, kind)   the domain keys that the flags give (a flag that is left out gives no key)
  defaults(kind)            the kind defaults, from templates/mod.json.tpl
  validate(domain, kind)    the normal form, or Fail rc 2 with one line and an example
  rows(domain, n)           fixture rows, the same values as fixture(n) in hooks/fixtures.ts
  texts(domain, kind, mod)  the TEXT of hooks/domain.ts (kind and mod: the about text and the text keys depend on them)
  lead(domain, row)         the row lead before the title: the mark glyph and the tag
  generate(cfg, wb)         every generated file, in memory: {path relative to wb: text}
  write(cfg, wb, ctx)       write them, run journey.py, write the marker tests, update cfg; return the paths
  check(cfg, wb)            drift lines; empty when the disk is in sync
  check_sections(cfg, wb)   a declared action or part with no section in a seeded file
  strip(text, keep, drop)   the section rule of the seeded files (design 1.6)
  cut_sections(wb, cfg)     new: cut the sections that the domain does not hold from the seeded files
  template_check(kind)      lint-skill: templates/<kind>/{hooks/domain.ts, hooks/fixtures.ts, types/index.d.ts} equal the output of the kind defaults
"""
