def pyl(text):
    """A Python string literal. The sentinels become names of journey.py: \\x01 is {P} (the pointer glyph of the picked variant)
    and \\x02 is {V} (its letter), so the literal is an f-string."""
    if '\x01' in text or '\x02' in text:
        return 'f' + repr(text.replace('{', '{{').replace('}', '}}')).replace('\\x01', '{P}').replace('\\x02', '{V}')
    return repr(text)


class JW:
    """The journey writer: it collects the scenarios, nodes and edges as Python source lines of journey.py."""

    def __init__(self):
        self.consts, self.sc, self.nodes, self.edges = [], [], [], []
        self.meta, self.out, self.start = {}, {}, {}

    def const(self, name, *anchors):
        self.consts.append(f'{name} = cite({", ".join(repr(a) for a in anchors)})')

    def scenario(self, sid, description, start, group=None):
        self.start[sid] = start
        self.sc.append(f'j.scenario({sid!r}, {description!r}, {start!r}' + (f', {group!r})' if group else ')'))

    @staticmethod
    def src(*names):
        names = [n for n in names if n]
        return names[0] if len(names) == 1 else "f'" + ', '.join('{' + n + '}' for n in names) + "'"

    def node(self, nid, area, title, desc, scn, marker, src, region=None, focus=None, shows=(), down=None, neg=None, esc2=False):
        extra = (f', region={region!r}' if region else '') + (f', focus={focus!r}' if focus else '')
        self.nodes.append(f'j.node({nid!r}, {area!r}, {title!r}, {desc!r}, {scn!r}, {pyl(marker)}, {src}{extra})')
        self.meta[nid] = {'scenario': scn, 'shows': list(shows), 'down': down, 'marker': marker, 'neg': neg, 'esc2': esc2}

    def twin(self, of, nid, scn, title, shows=None):
        self.nodes.append(f'j.twin({of!r}, {nid!r}, {scn!r}, title={title!r})')
        self.meta[nid] = dict(self.meta[of], scenario=scn)
        if shows is not None:
            self.meta[nid]['shows'] = list(shows)

    def edge(self, a, b, key, label, src, **kw):
        extra = ''
        for k in ('scn', 'onlyIn', 'notIn', 'history', 'approx', 'check', 'timeout'):
            if kw.get(k) is not None:
                v = kw[k]
                extra += f', {k}={pyl(v) if isinstance(v, str) else repr(v)}'
        self.edges.append(f'j.edge({a!r}, {b!r}, {pyl(key)}, {label!r}, {src}{extra})')
        for t in re.findall(r'text:"[^"]*"|\S+', key):
            self.out.setdefault(a, set()).add({'Up': 'Down'}.get(re.sub(r'\*\d+$', '', t), re.sub(r'\*\d+$', '', t)))

    def fan(self, a, b, key, label, src, check, approx='Same screen for another row or fixture.'):
        self.edge(a, b, key, label, src, scn=self.meta[a]['scenario'], approx=approx, check=check)

    def has(self, nid, key):
        return key in self.out.get(nid, set())


def say_text(m, row):
    """The Python twin of say() in hooks/domain.ts."""
    def piece(mt):
        parts = mt.group(1).split('|')
        v = row[parts[0]]
        return f'{v} {parts[1] if v == 1 else parts[2]}' if len(parts) == 3 else str(v)  # the number, then the word
    return re.sub(r'\{([^{}]*)\}', piece, m.d['say'])


