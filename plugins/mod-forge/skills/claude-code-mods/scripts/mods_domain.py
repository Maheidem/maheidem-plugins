def write(cfg, wb, ctx=None):
    """Write the generated files, run journey.py, write the marker tests, and update the scenarios, screens and noun of cfg.
    cfg is changed in place: the caller saves mod.json. Return the written paths."""
    m = model_of(cfg)
    cfg['domain'] = m.d
    written = []
    for rel, text in generate(cfg, wb).items():
        path = os.path.join(wb, rel)
        _write_text(path, text)
        written.append(path)
    cfg['scenarios'] = list(m.names)
    cfg['screens'] = screens(m)
    cfg['noun'] = noun_text(m.d)
    cfg['fixtures'] = None
    if m.kind != 'guard':
        jpy, jjs = os.path.join(wb, 'journey.py'), os.path.join(wb, 'journey.json')
        argv = [sys.executable, '-I', '-B', jpy, jjs, S]
        if ctx is not None:
            st = run_step(ctx, argv, cwd=wb, echo=False)
            rc, out = st.rc, st.out
        else:
            p = subprocess.run(argv, cwd=wb, capture_output=True, text=True)
            rc, out = p.returncode, p.stdout + p.stderr
        if rc != 0:
            raise Fail('journey.py (generated) failed: ' + ' | '.join(out.strip().split('\n')[-6:]), f'this is a generator bug: read {jpy}', 1)
        import mods_gen
        res = mods_gen.markers(wb, cfg)
        written += res['files']
    return written


