TAG = re.compile(r'\s*@([a-z][a-z0-9-]*)(?::(begin|end)\b)?')
GATED = ('action-', 'part-')


def tags_of(line):
    """The tags of a line: [(tag, 'begin'|'end'|None)] from its last '// @' comment. After @skip: or @real: the rest is free text."""
    i = line.rfind('// @')
    if i < 0:
        return []
    out, pos, tail = [], 0, line[i + 2:]
    while True:
        mt = TAG.match(tail, pos)
        if not mt:
            return out
        out.append((mt.group(1), mt.group(2)))
        pos = mt.end()
        if pos < len(tail) and tail[pos] == ':':
            return out  # free text follows (@skip: why, @real: code)


def strip(text, keep=None, drop=(), real=False, picked=None):
    """The section rule of the seeded files (design 1.6).

    A line whose trailing comment holds @<tag> belongs to that tag. A block runs from a // @<tag>:begin line to its // @<tag>:end line
    (both lines belong to it). Blocks of different tags may nest: a line belongs to every open block. A line is removed when one of
    its tags is in drop, or when it holds an action-* or part-* tag that keep does not name (keep None keeps them all).
    real=True turns each `// @real: <code>` line into <indent><code> and puts picked in place of {{picked}}.
    Other tags stay: @skip: is read by journey.py (auto_skips)."""
    drop = set(drop)
    out, stack = [], []
    for ln, line in enumerate(text.split('\n'), 1):
        tags = tags_of(line)
        belong = {t for t, _ in tags}
        for t, k in tags:
            if k == 'begin':
                if t in stack:
                    raise Fail(f'section @{t}:begin at line {ln} starts inside @{t}', 'none', 2)
                stack.append(t)
        belong |= set(stack)
        ends = [t for t, k in tags if k == 'end']
        for t in ends:
            if not stack or stack[-1] != t:
                raise Fail(f'section @{t}:end at line {ln} does not close the open section @{stack[-1] if stack else "(none)"}', 'none', 2)
        gone = any(t in drop or (keep is not None and t.startswith(GATED) and t not in keep) for t in belong)
        for t in ends:
            stack.pop()
        if gone:
            continue
        mt = re.match(r'^(\s*)// @real: ?(.*)$', line) if real else None
        if mt:
            line = mt.group(1) + mt.group(2)
        if real and picked is not None:
            line = line.replace('{{picked}}', picked)
        out.append(line)
    if stack:
        raise Fail(f'section @{stack[-1]}:begin has no :end line', 'none', 2)
    return '\n'.join(out)


def keep_set(m):
    """The section tags that the domain holds: action-<kind> for each declared action, part-<name> for each part."""
    return {f"action-{a['kind']}" for a in m.d['actions']} | {f'part-{p}' for p in m.parts}


def cut_sections(wb, cfg):
    """Cut the sections that the domain does not hold from the seeded files of src/<plugin>. Return the changed paths."""
    m = model_of(cfg)
    keep = keep_set(m)
    base = os.path.join(wb, 'src', m.plugin)
    changed = []
    for sub in ('hooks', 'tests'):
        for root, dirs, files in os.walk(os.path.join(base, sub)):
            dirs[:] = sorted(x for x in dirs if x not in ('kit', 'node_modules'))
            for f in sorted(files):
                if not f.endswith(('.ts', '.tsx')) or f.startswith('kit.') or f in ('flat.ts', 'fake.ts'):
                    continue
                p = os.path.join(root, f)
                old = _read(p)
                new = strip(old, keep=keep)
                if new != old:
                    _write_text(p, new)
                    changed.append(p)
    if m.kind in ('status-toast', 'command') and 'guard' not in m.parts:
        rules = os.path.join(base, 'hooks', 'rules.ts')
        if os.path.isfile(rules):
            os.remove(rules)
            changed.append(rules)
    return changed


