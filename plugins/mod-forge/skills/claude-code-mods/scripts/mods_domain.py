def parse_field(item, what='--fields'):
    """'name:type' -> a field dict. type: text | slug | path | name | age | number | enum(a|b) | enum(a=ok|b=err)."""
    name, _, typ = item.partition(':')
    name, typ = name.strip(), typ.strip()
    if not name or not typ:
        raise _bad(f"{what} '{item}': write name:type, for example name:slug")
    m = re.fullmatch(r'enum\((.*)\)', typ)
    if m:
        values, tones = [], {}
        for part in m.group(1).split('|'):
            v, _, t = part.strip().partition('=')
            v, t = v.strip(), t.strip()
            if v:
                values.append(v)
            if t:
                tones[v] = t
        if not 2 <= len(values) <= 8:
            raise _bad(f"{what} '{item}': an enum needs 2 to 8 members, for example enum(open|closed)")
        f = {'name': name, 'type': 'enum', 'values': values}
        if tones:
            f['tones'] = tones
        return f
    if typ not in FIELD_TYPES or typ == 'enum':
        raise _bad(f"{what} '{item}': the type must be one of text, slug, path, name, age, number, enum(a|b); for example name:slug")
    return {'name': name, 'type': typ}


def parse_fields(text, what='--fields'):
    out = [parse_field(x, what) for x in _split_top(text)]
    if not out and what == '--fields':
        raise _bad("--fields is empty: write name:type,..., for example 'name:slug,age:age'")
    return out


def parse_actions(text):
    """'d:delete,a:add,r:refresh,c:clear,d:done>state=done' -> action dicts. The kind comes from the verb, or from the set."""
    out = []
    for item in _split_top(text):
        head, _, setp = item.partition('>')
        key, _, verb = head.partition(':')
        key, verb = key.strip(), verb.strip()
        if not key or not verb:
            raise _bad(f"--actions '{item}': write key:verb, for example d:delete")
        act = {'key': key, 'verb': verb}
        if setp:
            fld, _, val = setp.partition('=')
            if not fld.strip() or not val.strip():
                raise _bad(f"--actions '{item}': after > write field=value, for example d:done>state=done")
            act.update(kind='mark', set={fld.strip(): val.strip()})
        else:
            kind = next((k for k, vs in VERBS.items() if verb in vs), None)
            if kind is None:
                raise _bad(f"--actions '{item}': the verb must be delete, remove, add, new, refresh, reload or clear; "
                           f"to set a field write key:verb>field=value, for example d:done>state=done")
            act['kind'] = kind
        out.append(act)
    return out


def parse_scenarios(text):
    out = []
    for item in _split_top(text):
        name, _, role = item.partition(':')
        name, role = name.strip(), role.strip()
        out.append({'name': name, 'role': role or (name if name in ROLES else 'normal')})
    return out


def parse_band(text):
    out = {}
    for item in _split_top(text):
        k, _, v = item.partition('=')
        k, v = k.strip(), v.strip()
        if k not in ('lead', 'counts', 'idle') or not v:
            raise _bad(f"--band '{item}': write lead=NAME, counts=NAME or idle=yield|show")
        out[k] = v
    return out


def parse_flags(args, kind):
    """The domain keys that the flags of new or domain give. A key that no flag gave is not in the result."""
    g = lambda name: getattr(args, name, None)
    out = {}
    if g('noun'):
        if not re.fullmatch(r'[a-z]+(:[a-z]+)?', g('noun')):
            raise _bad(f'--noun must be lowercase letters, as one or one:many (got "{g("noun")}")')
        out['noun'] = list(_noun_pair(g('noun')))
    if g('fields') is not None:
        out['fields'] = parse_fields(g('fields'))
    if g('title_field'):
        out['title'] = g('title_field')
    if g('detail_fields') is not None:
        out['detail'] = [x for x in _split_top(g('detail_fields'))]
    if g('actions') is not None:
        out['actions'] = parse_actions(g('actions')) if g('actions').strip() else []
    if g('scenarios'):
        out['scenarios'] = parse_scenarios(g('scenarios'))
    for flag, key in (('count', 'count'), ('overflow', 'overflow'), ('keep', 'keep')):
        if g(flag) is not None:
            out[key] = g(flag)
    if g('world') is not None:
        out['world'] = parse_fields(g('world'), '--world') if g('world').strip() else []
    if g('band'):
        out['band'] = parse_band(g('band'))
    for flag in ('say', 'on', 'probe'):
        if g(flag):
            out[flag] = g(flag)
    if g('parts') is not None:
        out['parts'] = [x for x in _split_top(g('parts'))]
    if g('text'):
        texts = {}
        for item in g('text'):
            k, eq, v = item.partition('=')
            if not eq or not k.strip():
                raise _bad(f"--text '{item}': write KEY=VALUE, for example --text 'error=The folder is not a git repository.'")
            texts[k.strip()] = v
        out['texts'] = texts
    return out


def defaults(kind):
    """The kind defaults: the domain object of the kind in templates/mod.json.tpl."""
    path = os.path.join(TEMPLATES, 'mod.json.tpl')
    try:
        with open(path, encoding='utf-8') as fh:
            d = json.load(fh)['kinds'][kind]['domain']
    except (OSError, ValueError, KeyError, TypeError) as e:
        raise Fail(f'{path} has no usable domain for kind {kind} ({type(e).__name__}: {e})', 'none', 2)
    if not isinstance(d, dict):
        raise Fail(f'kind {kind} has no domain block', 'none', 2)
    return copy.deepcopy(d)


def merge(base, given):
    """The base domain with the given keys replaced. A new field list resets what depends on it unless a flag sets that too."""
    d = copy.deepcopy(base)
    for k, v in given.items():
        if k == 'texts':
            d.setdefault('texts', {}).update(v)
        else:
            d[k] = v
    if 'scenarios' not in given and 'guard' in (given.get('parts') or []) and not any(s.get('role') == 'deny' for s in d.get('scenarios') or []):
        # The guard part needs a scenario that proves its refusal (role deny). The user gave no --scenarios: add the one that the part needs.
        taken = {s.get('name') for s in d.get('scenarios') or []}
        d['scenarios'] = list(d.get('scenarios') or []) + [{'name': next(n for n in ('blocked', 'refused', 'deny-probe') if n not in taken), 'role': 'deny'}]
    if 'fields' in given:
        names = {f['name'] for f in d['fields']}
        if 'title' not in given:
            d['title'] = None
        if 'detail' not in given:
            d['detail'] = None
        if 'actions' not in given:  # a mark action whose field is gone cannot apply
            d['actions'] = [a for a in d.get('actions') or [] if a.get('kind') != 'mark' or set((a.get('set') or {})) <= names]
        if 'band' not in given and d.get('band'):
            enums = [f for f in d['fields'] if f['type'] == 'enum']
            toned = [f for f in enums if f.get('tones')]
            pick = (toned or enums or [None])[0]
            d['band'] = dict(d['band'], counts=pick['name'] if pick else None)
    return d


# ---------------------------------------------------------------- validation


def _check_field(f, what, taken, world=False):
    if not isinstance(f, dict) or not NAME_RE.match(str(f.get('name'))):
        raise _bad(f"{what}: field name '{f.get('name') if isinstance(f, dict) else f}' must be lowercase letters and digits, "
                   f"starting with a letter, for example name or lastSeen")
    name, typ = f['name'], f.get('type')
    if name in taken:
        raise _bad(f"{what}: the field '{name}' is used twice")
    if name == 'id' or name in WORLD_KEYS or name in JS_WORDS:
        raise _bad(f"{what}: '{name}' is a reserved word; pick another field name")
    if typ not in FIELD_TYPES or (world and typ == 'enum'):
        raise _bad(f"{what}: '{name}' has type '{typ}'; use " + ('text, slug, path, name, age or number' if world else 'text, slug, path, name, age, number or enum(a|b)'))
    out = {'name': name, 'type': typ}
    if typ == 'enum':
        values, tones = f.get('values'), f.get('tones') or {}
        if not isinstance(values, list) or not 2 <= len(values) <= 8 or len(set(values)) != len(values):
            raise _bad(f"{what}: '{name}': an enum needs 2 to 8 members, for example enum(open|closed)")
        for v in values:
            if not isinstance(v, str) or not MEMBER_RE.match(v):
                raise _bad(f"{what}: '{name}': the member '{v}' must be letters, digits, - or _")
        if tones and (set(tones) != set(values) or any(t not in TONES for t in tones.values())):
            raise _bad(f"{what}: '{name}': a tone goes with every member and is ok, err, warn or muted, for example enum(open=warn|closed=ok)")
        if _pascal(name) in RESERVED_TYPES:
            raise _bad(f"{what}: the enum field '{name}' would make the type {_pascal(name)}, which the contract uses; pick another name")
        out['values'] = list(values)
        if tones:
            out['tones'] = {v: tones[v] for v in values}
    elif f.get('values') is not None:
        vals = f['values']
        if not isinstance(vals, list) or not vals or not all(isinstance(x, str) and x for x in vals):
            raise _bad(f"{what}: '{name}': values must be a list of strings")
        out['values'] = list(vals)
    return out


def validate(domain, kind):
    """The normal form of a domain block, or Fail rc 2. kind is a kind of DOMAIN_KINDS."""
    if kind not in DOMAIN_KINDS:
        raise _bad(f'kind {kind} has no domain block (kind mixed keeps the round 1 path)')
    if not isinstance(domain, dict):
        raise _bad('the domain block must be an object')
    src = domain
    pane, nopane = kind in PANE_KINDS, kind in NOPANE_KINDS
    d = {'v': 1}

    # noun
    if kind == 'guard':
        d['noun'] = None
    else:
        noun = src.get('noun')
        if isinstance(noun, str):
            noun = list(_noun_pair(noun))
        if not (isinstance(noun, list) and len(noun) == 2 and all(isinstance(x, str) and NOUN_RE.match(x) for x in noun)):
            raise _bad("noun must be one lowercase word, or one:many, for example branch or person:people")
        d['noun'] = list(noun)

    # fields
    fields, taken = [], set()
    if kind == 'guard':
        if src.get('fields'):
            raise _bad('a guard has no fields')
    else:
        if not src.get('fields'):
            raise _bad("the domain needs at least one field: --fields 'name:type,...', for example --fields 'name:slug,age:age'")
        for f in src['fields']:
            nf = _check_field(f, 'fields', taken)
            fields.append(nf)
            taken.add(nf['name'])
    d['fields'] = fields
    by = {f['name']: f for f in fields}

    # title and detail
    title = src.get('title')
    if pane:
        title = title or next((f['name'] for f in fields if f['type'] in TITLE_TYPES), None)
        if title is None:
            raise _bad("no field can be the title: add a text, slug, path or name field, or name it with --title-field")
        if title not in by or by[title]['type'] not in TITLE_TYPES:
            raise _bad(f"--title-field {title}: the title must be a field of type text, slug, path or name; fields: {', '.join(by) or 'none'}")
    else:
        title = title if title in by else None
    d['title'] = title
    detail = src.get('detail')
    if kind in ('pane-simple', 'status-toast', 'command', 'guard'):
        detail = []
    elif detail is None:
        detail = [f['name'] for f in fields if f['name'] != title]
    for n in detail:
        if n not in by:
            raise _bad(f"--detail-fields {n}: no such field; fields: {', '.join(by)}")
        if n == title:
            raise _bad(f"--detail-fields {n}: the detail view shows the title already; leave it out")
    if len(set(detail)) != len(detail):
        raise _bad('--detail-fields names a field twice')
    d['detail'] = list(detail)

    # actions
    actions, kinds_seen, keys_seen = [], set(), set()
    for a in src.get('actions') or []:
        if not isinstance(a, dict):
            raise _bad('an action is an object: {key, verb, kind}')
        key, verb, akind = a.get('key'), a.get('verb'), a.get('kind')
        label = f'{key}:{verb}'
        if akind not in ACTION_KINDS:
            raise _bad(f"--actions '{label}': kind must be one of {', '.join(ACTION_KINDS)}")
        if akind not in KIND_ACTIONS[kind]:
            if kind == 'pane-simple':
                raise _bad(f'pane-simple has no selection: use pane-list for {label}')
            raise _bad(f"--actions '{label}': kind {kind} has no {akind} action")
        if not (isinstance(key, str) and re.fullmatch(r'[a-z]', key)) or key in ('y', 'n'):
            raise _bad(f"--actions '{label}': the key must be one lowercase letter, not y or n (they answer a confirm), for example d")
        if key in keys_seen:
            raise _bad(f"--actions: the key '{key}' is used twice")
        if akind in kinds_seen:
            raise _bad(f"--actions: the action kind {akind} is declared twice")
        if not (isinstance(verb, str) and re.fullmatch(r'[a-z]+', verb)):
            raise _bad(f"--actions '{label}': the verb must be lowercase letters")
        if akind in VERBS and verb not in VERBS[akind]:
            raise _bad(f"--actions '{label}': for {akind} the verb is {' or '.join(VERBS[akind])}")
        na = {'key': key, 'verb': verb, 'kind': akind}
        if akind == 'mark':
            st = a.get('set')
            if not (isinstance(st, dict) and len(st) >= 1):
                raise _bad(f"--actions '{label}': a mark action sets a field: write key:verb>field=value, for example d:done>state=done")
            for fld, val in st.items():
                if fld not in by:
                    raise _bad(f"--actions '{label}': the field '{fld}' does not exist; fields: {', '.join(by)}")
                if by[fld]['type'] == 'enum' and val not in by[fld]['values']:
                    raise _bad(f"--actions '{label}': '{val}' is not a member of {fld}: {', '.join(by[fld]['values'])}")
                if by[fld]['type'] == 'number':
                    raise _bad(f"--actions '{label}': a mark action sets a text or an enum field, not a number")
            na['set'] = dict(st)
        actions.append(na)
        kinds_seen.add(akind)
        keys_seen.add(key)
    d['actions'] = actions

    # world and band
    world, wtaken = [], set()
    if src.get('world'):
        if not pane:
            raise _bad(f'--world is for pane-list, pane-simple and band, not {kind}')
        for f in src['world']:
            nf = _check_field(f, '--world', wtaken, world=True)
            world.append(nf)
            wtaken.add(nf['name'])
    d['world'] = world
    band = src.get('band')
    if kind == 'band':
        band = band or {}
        lead, counts, idle = band.get('lead'), band.get('counts'), band.get('idle') or 'show'
        if lead is not None and lead not in wtaken:
            raise _bad(f"--band lead={lead}: the lead names a world field; add it with --world '{lead}:slug'")
        if counts is not None:
            if counts not in by or by[counts]['type'] != 'enum':
                raise _bad(f"--band counts={counts}: the counts name an enum field; fields: {', '.join(by)}")
            toned = next((f['name'] for f in fields if f['type'] == 'enum' and f.get('tones')), None)
            if by[counts].get('tones') and counts != toned:
                raise _bad(f"--band counts={counts}: only the first enum field with tones ({toned}) can set the band tones; put {counts} first")
        if idle not in ('yield', 'show'):
            raise _bad(f"--band idle={idle}: use yield or show")
        d['band'] = {'lead': lead, 'counts': counts, 'idle': idle}
    else:
        if band:
            raise _bad('--band is for kind band only')
        d['band'] = None

    # scenarios, count, overflow
    scenarios, names = [], set()
    if not src.get('scenarios'):
        raise _bad("the domain needs at least one scenario: --scenarios 'normal,empty'")
    for s in src['scenarios']:
        name, role = (s.get('name'), s.get('role')) if isinstance(s, dict) else (None, None)
        if not (isinstance(name, str) and SCN_RE.match(name)):
            raise _bad(f"scenario name '{name}' must be lowercase letters, digits and -, for example save-fails")
        if name in names:
            raise _bad(f"the scenario '{name}' is used twice")
        if role not in ROLES:
            raise _bad(f"--scenarios {name}:{role}: the role must be one of {', '.join(KIND_ROLES[kind])}")
        if role not in KIND_ROLES[kind]:
            raise _bad(f"--scenarios {name}:{role}: kind {kind} has the roles {', '.join(KIND_ROLES[kind])}")
        if role == 'fails' and not actions:
            raise _bad(f"--scenarios {name}:fails needs an action that can fail: add --actions")
        if role == 'idle' and (d['band'] or {}).get('idle') != 'yield':
            raise _bad(f"--scenarios {name}:idle needs --band idle=yield")
        names.add(name)
        scenarios.append({'name': name, 'role': role})
    roles = [s['role'] for s in scenarios]
    if kind != 'guard' and 'normal' not in roles:
        raise _bad("one scenario needs the role normal, for example --scenarios 'normal,empty'")
    d['scenarios'] = scenarios
    count, overflow = src.get('count'), src.get('overflow')
    if kind == 'guard':
        count = overflow = None
    else:
        lo = 2 if pane else 1
        if not (isinstance(count, int) and not isinstance(count, bool) and lo <= count <= 14):
            raise _bad(f'--count must be an integer from {lo} to 14 (got {count!r})')
        if pane:
            if not (isinstance(overflow, int) and not isinstance(overflow, bool) and overflow >= 31 and overflow > count):
                raise _bad(f'--overflow must be an integer of 31 or more, above --count (the window of a 45-row dock shows 31 rows); got {overflow!r}')
        else:
            overflow = None
    d['count'], d['overflow'] = count, overflow

    # no-pane keys
    parts = src.get('parts') or []
    if pane:
        if parts:
            raise _bad(f'--parts is for status-toast, command and guard, not {kind}')
        for flag in ('say', 'on', 'probe'):
            if src.get(flag):
                raise _bad(f'--{flag} is for status-toast, command and guard, not {kind}')
        parts = []
        say = on = probe = None
        keep = src.get('keep') if isinstance(src.get('keep'), int) else 5
    else:
        parts = [p for p in PARTS if p in parts]
        bad = [p for p in (src.get('parts') or []) if p not in PARTS]
        if bad:
            raise _bad(f"--parts {','.join(bad)}: use toast, command or guard")
        if not parts:
            parts = [KIND_PARTS[kind][0]]
        off = [p for p in parts if p not in KIND_PARTS[kind]]
        if off:
            raise _bad(f"--parts {','.join(off)}: kind {kind} has the parts {', '.join(KIND_PARTS[kind])}")
        if kind == 'status-toast' and 'toast' not in parts:
            raise _bad('kind status-toast needs the part toast: --parts toast,command')
        if kind == 'command' and 'command' not in parts:
            raise _bad('kind command needs the part command: --parts command,guard')
        if kind == 'guard' and parts != ['guard']:
            raise _bad('kind guard has the part guard only')
        keep = src.get('keep') if src.get('keep') is not None else 5
        if not (isinstance(keep, int) and not isinstance(keep, bool) and 1 <= keep <= 20) and kind != 'guard':
            raise _bad(f'--keep must be an integer from 1 to 20 (got {keep!r})')
        say = on = None
        if kind == 'guard' and (src.get('say') or src.get('on')):
            raise _bad('a guard has no rows: --say and --on are for status-toast and command')
        if kind != 'guard':
            say = src.get('say') or '{' + (title or fields[0]['name']) + '}'
            for m in re.finditer(r'\{([^{}]*)\}', say):
                parts_ = m.group(1).split('|')
                if parts_[0] not in by:
                    raise _bad(f"--say '{say}': {{{parts_[0]}}} is not a field; fields: {', '.join(by)}")
                if len(parts_) not in (1, 3) or (len(parts_) == 3 and by[parts_[0]]['type'] != 'number'):
                    raise _bad(f"--say '{say}': write {{field}} or {{numberField|one|many}}, for example {{tools|tool call|tool calls}}")
            on = src.get('on') or 'tool.call'
            if on not in EVENTS:
                raise _bad(f"--on {on}: use {', '.join(EVENTS)}")
        probe = src.get('probe') or 'rm -rf {dir}'
        if '{dir}' not in probe:
            raise _bad("--probe must hold {dir}, the folder that must stay, for example 'rm -rf {dir}'")
        if 'deny' in roles and 'guard' not in parts:
            raise _bad('a scenario with the role deny needs the part guard: --parts toast,guard')
    d['say'], d['on'], d['parts'], d['keep'] = say, on, parts, (None if kind == 'guard' else keep)
    d['probe'] = probe if nopane else None

    # texts
    allowed = TEXT_KEYS['pane' if pane else kind]
    texts = src.get('texts') or {}
    for k, v in texts.items():
        if k not in allowed:
            raise _bad(f"--text {k}=...: unknown key; the keys of kind {kind} are {', '.join(allowed)}")
        if not isinstance(v, str):
            raise _bad(f"--text {k}: the value must be a string")
    d['texts'] = dict(texts)
    return d


# ---------------------------------------------------------------- the model: derived data of a domain


class Model:
    """A validated domain with the data that the generators share."""

    def __init__(self, d, kind, mod, plugin=None, rows_dock=45):
        self.d, self.kind, self.mod = d, kind, mod
        self.plugin = plugin or f'{mod}-proto'
        self.pane = kind in PANE_KINDS
        self.rows_dock = rows_dock
        self.fields = d['fields']
        self.by = {f['name']: f for f in self.fields}
        self.noun = d['noun'] or ['item', 'items']
        self.one, self.many = self.noun
        self.act = {a['kind']: a for a in d['actions']}
        self.scenarios = d['scenarios']
        self.names = [s['name'] for s in self.scenarios]
        self.parts = d['parts']
        self.variants = ['A', 'B', 'C', 'D'] if self.pane else ['A']
        self.tone_field = next((f for f in self.fields if f['type'] == 'enum' and f.get('tones')), None)
        self.tag_fields = [f for f in self.fields if f['type'] == 'enum' and not f.get('tones')]
        self.words = _words()
        self._texts = None

    # --- scenarios
    def first(self, role):
        return next((s['name'] for s in self.scenarios if s['role'] == role), None)

    # --- rows
    def values(self, f):
        """The fixture values of a field (the list that fixtures.ts holds), or None for a number."""
        t = f['type']
        if t == 'number':
            return None
        if t == 'enum':
            return f['values']
        if f.get('values'):
            return f['values']
        w = self.words
        return {'text': w['sentences'], 'slug': w['slugs'], 'path': w['paths'], 'name': w['names'], 'age': w['ages']}[t]

    def value(self, f, i):
        t, vals = f['type'], self.values(f)
        if t == 'number':
            return i * 3 + 1
        if t in ('enum', 'name'):
            return vals[i % len(vals)]
        if i < len(vals):
            return vals[i]
        if t == 'age':
            return vals[-1] if f.get('values') else '1mo'
        return {'text': f'Older {self.one} {i + 1}', 'slug': f'{self.one}-{i + 1}', 'path': f'src/{self.one}-{i + 1}.ts'}[t]

    def rows(self, n):
        return [dict({'id': f'r{i}'}, **{f['name']: self.value(f, i) for f in self.fields}) for i in range(n)]

    def world_value(self, f):
        return self.value(f, 0)

    # --- row text, the Python twins of the helpers of hooks/domain.ts
    def title_of(self, r):
        return str(r[self.d['title']])

    def lead(self, r):
        tf = self.tone_field
        out = f"{MARK[tf['tones'][r[tf['name']]]]} " if tf else ''
        tags = [str(r[f['name']]) for f in self.tag_fields]
        return out + (' '.join(tags) + ' ' if tags else '')

    def side_fields(self):
        return [f for f in self.fields if f['type'] in ('age', 'number') and f['name'] != self.d['title']]

    def ago(self, v):
        return 'just now' if v == 'now' else f'{v} ago'

    def detail_parts(self):
        """(plain field or None, dim fields) of the detail view: the first text field is a plain line, the rest one dim line."""
        names = self.d['detail']
        plain = next((n for n in names if self.by[n]['type'] == 'text'), None)
        return plain, [n for n in names if n != plain]

    def detail_lines(self, r):
        plain, dim = self.detail_parts()
        out = []
        if plain:
            out.append(str(r[plain]))
        if dim:
            out.append(' · '.join(self.ago(r[n]) if self.by[n]['type'] == 'age' else str(r[n]) for n in dim))
        return out

    def new_row(self, text):
        r = {'id': 'new0'}
        for f in self.fields:
            t = f['type']
            r[f['name']] = text if f['name'] == self.d['title'] else ('now' if t == 'age' else 0 if t == 'number' else f['values'][0] if t == 'enum' else '')
        return r

    def marked(self, r):
        a = self.act.get('mark')
        return dict(r, **a['set']) if a else r

    def count_text(self, n):
        return f"{n} {self.one if n == 1 else self.many}"

    def row_text(self, r, pointer=True):
        """The screen text of a row up to the end of its title: <pointer> <mark> <tag> <title>, the title cut at a word end."""
        return ('\x01 ' if pointer else '') + self.lead(r) + cut_word(self.title_of(r), 24)

    # --- texts
    def texts(self):
        if self._texts is None:
            self._texts = _texts(self)
        return self._texts

    def counts_field(self):
        b = self.d['band'] or {}
        return self.by.get(b.get('counts')) if b.get('counts') else None


def _texts(m):
    d, kind = m.d, m.kind
    one, many = m.one, m.many
    a = _article(one)
    cap = lambda s: s[:1].upper() + s[1:]
    dverb = (m.act.get('delete') or {}).get('verb', 'delete')
    past = {'delete': {'delete': 'deleted', 'remove': 'removed'}.get(dverb, 'deleted')}
    mark = m.act.get('mark')
    marked = f"Marked {list(mark['set'].values())[0]}" if mark else 'Marked done'
    about = {'pane-list': f'A pane of {many}', 'pane-simple': f'A pane of {many}', 'band': f'A band of {many} above the prompt',
             'status-toast': f'Toasts about {many}', 'command': f'A /{m.mod} command for {many}', 'guard': 'A guard for Bash calls'}[kind]
    full = {
        'about': about,
        'title': cap(many),
        'empty': f'No {many} yet',
        'loadingWhat': many,
        'error': f'The {many} could not be read.',
        'errorSubject': 'Read failed',
        'errorHint': f'No {many} show until a read works.',
        'askDelete': f'{cap(dverb)} this {one}?',
        'pendingDelete': f'Deleting the {one}…',
        'pendingAdd': f'Saving the {one}…',
        'pendingRefresh': f'Reading the {many}…',
        'pendingClear': f'Clearing the {many}…',
        'pendingMark': f'Saving the {one}…',
        'doneDelete': cap(past['delete']),
        'doneAdd': 'Saved',
        'doneRefresh': 'Read again',
        'doneClear': 'Cleared',
        'doneMark': marked,
        'failedDelete': f'The {one} was not {past["delete"]}. The store write failed.',
        'failedAdd': f'The {one} was not saved. The store write failed. Your text is kept.',
        'failedRefresh': f'The {many} were not read again. The read failed.',
        'failedClear': f'The {many} were not cleared. The store write failed.',
        'failedMark': f'The {one} was not saved. The store write failed.',
        'addTitle': f'New {one}',
        'addPlaceholder': f'Type {a} {one}',
        'addEmpty': f'The {one} is empty. Type some text, then press Enter.',
        'addBanner': f'The last {one} was not saved · the store write failed',
        'historyHead': f'Last {d["keep"]} {many}:' if d.get('keep') else '',
        'refused': 'Refused',
    }
    keys = TEXT_KEYS['pane' if m.pane else kind]
    out = {k: full[k] for k in keys}
    out.update(d['texts'])
    return out


def texts(domain, kind='pane-list', mod='mod'):
    return Model(domain, kind, mod).texts()


def rows(domain, n, kind='pane-list'):
    return Model(domain, kind, 'mod').rows(n)


def lead(domain, row, kind='pane-list'):
    return Model(domain, kind, 'mod').lead(row)


