def screens(m):
    """The extra screens of a mockups pass (design 1.5.5): at most 4 of the first normal scenario, 'name=scenario:keys[|focus=TEXT]'."""
    if not m.pane:
        return []
    n = m.first('normal')
    out = []
    if m.kind != 'pane-simple':
        out.append(f'detail-{n}={n}:Enter')
    for a in m.d['actions']:
        k = a['kind']
        if k == 'delete':
            out.append(f"confirm-{n}={n}:{a['key']}|focus=n: cancel")
        elif k == 'add':
            out.append(f"add-{n}={n}:{a['key']}")
        elif k == 'clear':
            out.append(f"list-{n}-cleared={n}:{a['key']}")
        elif k == 'mark':
            out.append(f"list-{n}-marked={n}:{a['key']}")
    ov = m.first('overflow')
    if ov and m.kind != 'pane-simple':
        out.append(f'list-{ov}-mid={ov}:Down*5')
    return out[:4]


def noun_text(d):
    """mod.json keeps the noun as one:many (new-mod.sh and _grep_left read it). The template noun is not a noun to rename: null."""
    noun = d.get('noun')
    if not noun or list(noun) == ['item', 'items']:
        return None
    return f'{noun[0]}:{noun[1]}'


