# ---------------------------------------------------------------- small helpers (also used by mods_setup.py)


def plural(one):
    """The English plural of a noun: branch -> branches, box -> boxes, entry -> entries, note -> notes."""
    if re.search(r'(s|x|z|ch|sh)$', one):
        return one + 'es'
    if re.search(r'[^aeiou]y$', one):
        return one[:-1] + 'ies'
    return one + 's'


def _noun_pair(noun):
    """'note' or 'note:notes' -> ('note', 'notes'). None -> None. 'one:many' sets an irregular plural."""
    if not noun:
        return None
    one, _, many = noun.partition(':')
    return one, many or plural(one)


def _ts(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def _ts_list(name, items, typ=''):
    """A const list in the template style: one line up to 110 characters, else one item per line."""
    head = f'const {name}{typ} = ['
    one = head + ', '.join(_ts(x) for x in items) + ']'
    if len(one) <= 110:
        return one + '\n'
    return head + '\n' + ''.join(f'  {_ts(x)},\n' for x in items) + ']\n'


def _write_text(path, text):
    """Write a file, read it back, compare. A difference is Fail (a write that returns may store nothing)."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)
    with open(path, encoding='utf-8') as fh:
        if fh.read() != text:
            raise Fail(f'read-back of {path} differs from what was written')


def _read(path):
    try:
        with open(path, encoding='utf-8') as fh:
            return fh.read()
    except OSError:
        return None


def _key(k, audit=False):
    """An object key in TypeScript: bare when it is an identifier, else quoted. audit=True quotes `deny` too:
    audit-handlers.py lists a line that holds `deny:` (a refusal), and hooks/domain.ts must hold no listed line."""
    return k if re.fullmatch(r'[A-Za-z_$][\w$]*', k) and not (audit and k == 'deny') else _ts(k)


def _pascal(name):
    return name[:1].upper() + name[1:]


def _snake(name):
    return re.sub(r'([A-Z])', r'_\1', name).upper()


def _article(noun):
    return 'an' if noun[:1] in 'aeiou' else 'a'


def _split_top(text, sep=','):
    """Split on sep outside parentheses."""
    out, depth, cur = [], 0, ''
    for ch in text:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return [x.strip() for x in out if x.strip()]


def cut_word(text, n):
    """The first n characters of a text, cut at a word end (the marker rule of design 1.5.4)."""
    if len(text) <= n:
        return text
    if text[n] == ' ':
        return text[:n].rstrip()
    sp = text[:n].rfind(' ')
    return text[:sp].rstrip() if sp > 0 else text[:n]


def marker_text(text, n):
    """A text for a journey marker: cut at a word end, with no closing punctuation."""
    return cut_word(text, n).rstrip('.,;:!?')


def _words():
    path = os.path.join(TEMPLATES, 'fixtures', 'words.json')
    try:
        with open(path, encoding='utf-8') as fh:
            w = json.load(fh)
        for k in ('sentences', 'ages', 'slugs', 'paths', 'names'):
            if not (isinstance(w[k], list) and w[k] and all(isinstance(x, str) for x in w[k])):
                raise ValueError(f'{k} must be a list of strings')
        return w
    except (OSError, ValueError, KeyError) as e:
        raise Fail(f'cannot use {path}: {e}', 'none', 2)


